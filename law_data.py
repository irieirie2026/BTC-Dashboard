def _now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _counts(jurisdictions: list[dict]) -> dict[str, int]:
    out = {k: 0 for k in STATUS_META}
    for j in jurisdictions:
        s = j.get("status") or "unclear"
        if s not in out:
            s = "unclear"
        out[s] += 1
    return out


def _index_by_id() -> dict[str, dict]:
    return {j["id"]: j for j in JURISDICTIONS}


def get_jurisdiction(slug: str) -> dict | None:
    if not slug:
        return None
    key = slug.strip().lower().replace("_", "-")
    by_id = _index_by_id()
    if key in by_id:
        return by_id[key]
    for j in JURISDICTIONS:
        if j.get("iso2", "").lower() == key or j.get("iso3", "").lower() == key:
            return j
        if j["name"].lower() == key:
            return j
    return None


